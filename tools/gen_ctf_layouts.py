"""Regenerate tools/ctf_layouts.py from Zephyr's subsys/tracing/ctf/ctf_top.h.

Usage: ZEPHYR_BASE=~/zephyrproject/zephyr python3 tools/gen_ctf_layouts.py

Each ctf_top_*() emitter is CTF_EVENT(CTF_LITERAL(uint16_t, ID), f1, f2, ...)
with the fields packed in that order after the uint32 timestamp; the
parameter list gives each field's type.
"""

import os
import re
import sys
from pathlib import Path

SIZES = {"uint32_t": 4, "int32_t": 4, "int": 4, "uint16_t": 2, "int8_t": 1, "uint8_t": 1}
STRINGS = {"ctf_bounded_string_t": "CTF_MAX_STRING_LEN", "ctf_net_bounded_string_t": "CTF_NET_MAX_STRING_LEN"}

base = Path(os.environ.get("ZEPHYR_BASE", "")) / "subsys/tracing/ctf/ctf_top.h"
if not base.is_file():
    sys.exit(f"set ZEPHYR_BASE (looked for {base})")
src = base.read_text()

consts = {"CTF_MAX_STRING_LEN": int(re.search(r"#define CTF_MAX_STRING_LEN (\d+)", src)[1])}
consts["CTF_NET_MAX_STRING_LEN"] = consts["CTF_MAX_STRING_LEN"]  # #define'd as the same
ids = {m[1]: int(m[2], 16) for m in re.finditer(r"(CTF_EVENT_\w+)\s*=\s*(0x[0-9A-Fa-f]+)", src)}

rows = {}
for m in re.finditer(r"static inline void ctf_top_\w+\(([^)]*)\)\s*\{\s*CTF_EVENT\("
                     r"CTF_LITERAL\(uint16_t,\s*(CTF_EVENT_\w+)\)\s*,?\s*([^;]*)\);", src, re.S):
    params, ev, fields = m[1], m[2], m[3]
    types = {}
    for p in params.split(","):
        p = p.strip()
        if p and p != "void":
            *t, n = p.split()
            types[n.strip("*")] = " ".join(t)
    layout = []
    for f in (f.strip().rstrip(")") for f in fields.replace("\n", " ").split(",") if f.strip()):
        t = types[f]
        if t in STRINGS:
            layout.append((f, "str", consts[STRINGS[t]]))
        else:
            layout.append((f, "int" if t.startswith("int") else "uint", SIZES[t]))
    rows[ids[ev]] = (ev[len("CTF_EVENT_"):].lower(), layout)

out = ['"""CTF event layouts, generated by tools/gen_ctf_layouts.py from Zephyr',
       f'v4.4.2 subsys/tracing/ctf/ctf_top.h. Do not edit by hand.',
       '',
       'Every event: uint32 timestamp (ns), uint16 id, then these fields, packed,',
       'little-endian. (name, "uint" | "int" | "str", size in bytes)',
       '"""', '', 'LAYOUTS = {']
for i in sorted(rows):
    name, layout = rows[i]
    out.append(f"    {i:#06x}: ({name!r}, {layout!r}),")
out.append("}")
Path(__file__).with_name("ctf_layouts.py").write_text("\n".join(out) + "\n")
print(f"{len(rows)} event layouts")
